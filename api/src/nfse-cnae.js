const norm = s => String(s || '').normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase();
const PARADAS = new Set('de da do das dos e em para por com sem ou a o as os na no nas nos ao aos servico servicos atividade atividades outros outras outro qualquer natureza geral inclusive exceto nao especificadas anteriormente'.split(' '));
