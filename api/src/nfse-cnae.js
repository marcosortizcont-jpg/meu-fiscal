// códigos sugeridos para a atividade, do mais provável ao menos
export function sugerirPorCnae(cnaes) {
  const out = [];
  for (const c of [].concat(cnaes || [])) {
    const d = String(c || '').replace(/\D/g, ''); if (d.length < 4) continue;
    for (const k of [d.slice(0, 7), d.slice(0, 4)]) for (const cod of CNAE_SERVICO[k] || []) if (!out.includes(cod)) out.push(cod);
  }
  return out;
}
